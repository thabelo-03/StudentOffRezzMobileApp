export const buildPropertiesHTML = (listings, dateRange) => {
  const totalSpots = listings.reduce((a, h) => a + (Number(h.availableSpots) || 0), 0);
  const avgPrice = listings.length > 0 ? (listings.reduce((a, h) => a + (Number(h.price) || 0), 0) / listings.length).toFixed(0) : '0';

  const stats = buildStatCards([
    { label: 'Total Properties', value: listings.length, color: '#3182ce' },
    { label: 'Available Spots', value: totalSpots, color: '#38a169' },
    { label: 'Avg Price', value: 'R' + avgPrice, color: '#dd6b20' },
  ]);

  const table = buildTable(
    ['#', 'Property Title', 'Location', 'Price', 'Spots', 'Gender'],
    listings.map((h, i) => [i + 1, h.title || 'N/A', h.location || 'N/A', 'R' + (h.price || 0), h.availableSpots || 0, h.genderPolicy || 'Mixed'])
  );

  return buildHTML('Properties Report', listings.length + ' properties listed', dateRange,
    stats + '<div class="section-title">Property Listings</div>' + table);
};

export const buildBookingsHTML = (bookings, dateRange) => {
  const pending = bookings.filter(b => b.status === 'pending').length;
  const accepted = bookings.filter(b => b.status === 'accepted').length;
  const paid = bookings.filter(b => b.status === 'paid').length;
  const rejected = bookings.filter(b => b.status === 'rejected').length;

  const stats = buildStatCards([
    { label: 'Pending', value: pending, color: '#d69e2e' },
    { label: 'Accepted', value: accepted, color: '#38a169' },
    { label: 'Paid', value: paid, color: '#3182ce' },
    { label: 'Rejected', value: rejected, color: '#e53e3e' },
  ]);

  const table = buildTable(
    ['#', 'Property', 'Student', 'Amount', 'Status', 'Date'],
    bookings.map((b, i) => [
      i + 1, b.houseName || b.houseTitle || 'N/A', b.studentEmail || b.studentName || 'N/A',
      'R' + (b.amount || 0), statusBadge(b.status),
      b.timestamp ? new Date(b.timestamp).toLocaleDateString() : 'N/A'
    ])
  );

  return buildHTML('Booking Summary', bookings.length + ' total bookings', dateRange,
    stats + '<div class="section-title">All Bookings</div>' + table);
};

export const buildRevenueHTML = (bookings, dateRange) => {
  const paidBookings = bookings.filter(b => b.status === 'paid');
  const totalRevenue = paidBookings.reduce((a, b) => a + (Number(b.amount) || 0), 0);
  const avgTx = paidBookings.length > 0 ? (totalRevenue / paidBookings.length).toFixed(0) : '0';

  const stats = buildStatCards([
    { label: 'Total Revenue', value: 'R' + totalRevenue, color: '#38a169' },
    { label: 'Transactions', value: paidBookings.length, color: '#3182ce' },
    { label: 'Average', value: 'R' + avgTx, color: '#dd6b20' },
  ]);

  const rows = paidBookings.map((b, i) => [
    i + 1, b.houseName || b.houseTitle || 'N/A', b.studentEmail || 'N/A',
    'R' + (b.amount || 0), b.transactionId || 'N/A',
    b.paymentDate ? new Date(b.paymentDate).toLocaleDateString() : 'N/A'
  ]);
  rows.push({ _total: true, cells: ['', '', '', '<b>R' + totalRevenue + '</b>', '', '<b>TOTAL</b>'] });

  const table = buildTable(['#', 'Property', 'Student', 'Amount', 'Trans ID', 'Date'], rows);

  return buildHTML('Revenue Report', 'Total Revenue: R' + totalRevenue, dateRange,
    stats + '<div class="section-title">Payment Transactions</div>' + table);
};

export const buildPlatformOverviewHTML = (users, houses, dateRange) => {
  const students = users.filter(u => u.role === 'student').length;
  const landlords = users.filter(u => u.role === 'landlord').length;
  const admins = users.filter(u => u.role === 'admin').length;

  const stats = buildStatCards([
    { label: 'Total Users', value: users.length, color: '#3182ce' },
    { label: 'Students', value: students, color: '#38a169' },
    { label: 'Landlords', value: landlords, color: '#dd6b20' },
    { label: 'Listings', value: houses.length, color: '#805ad5' },
  ]);

  const locationCounts = {};
  houses.forEach(h => { const loc = h.location || 'Unknown'; locationCounts[loc] = (locationCounts[loc] || 0) + 1; });
  const locRows = Object.entries(locationCounts).map(([loc, count]) => [loc, count, ((count / (houses.length || 1)) * 100).toFixed(1) + '%']);
  const locTable = buildTable(['Location', 'Listings', 'Share'], locRows);

  const usersTotal = users.length || 1;
  const roleTable = buildTable(['Role', 'Count', 'Share'], [
    ['Students', students, ((students / usersTotal) * 100).toFixed(1) + '%'],
    ['Landlords', landlords, ((landlords / usersTotal) * 100).toFixed(1) + '%'],
    ['Admins', admins, ((admins / usersTotal) * 100).toFixed(1) + '%'],
  ]);

  return buildHTML('Platform Overview', 'System snapshot', dateRange,
    stats + '<div class="section-title">Listings by Location</div>' + locTable +
    '<div class="section-title">User Distribution</div>' + roleTable);
};

