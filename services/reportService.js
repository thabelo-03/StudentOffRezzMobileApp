const escapeCSV = (val) => {
  const str = String(val != null ? val : '');
  if (str.indexOf(',') >= 0 || str.indexOf('"') >= 0 || str.indexOf('\n') >= 0) {
    return '"' + str.replace(/"/g, '""') + '"';
  }
  return str;
};

export const generateCSV = async (headers, rows, filename) => {
  try {
    const lines = [];
    lines.push(headers.map(escapeCSV).join(','));
    for (let i = 0; i < rows.length; i++) {
      lines.push(rows[i].map(escapeCSV).join(','));
    }
    const csvContent = lines.join('\n');

    if (Platform.OS === 'web') {
      try {
        const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
        const url = URL.createObjectURL(blob);
        const link = document.createElement('a');
        link.setAttribute('href', url);
        link.setAttribute('download', filename + '.csv');
        link.style.visibility = 'hidden';
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);
        setTimeout(function() { URL.revokeObjectURL(url); }, 1000);
      } catch (webErr) {
        console.error('Web CSV Error:', webErr);
      }
    } else {
      const fileUri = FileSystem.documentDirectory + filename + '.csv';
      await FileSystem.writeAsStringAsync(fileUri, csvContent, { encoding: FileSystem.EncodingType.UTF8 });
      const canShare = await Sharing.isAvailableAsync();
      if (canShare) {
        await Sharing.shareAsync(fileUri, { mimeType: 'text/csv', dialogTitle: 'Export ' + filename, UTI: 'public.comma-separated-values-text' });
      } else {
        Alert.alert('Success', 'Report saved successfully.');
      }
    }
  } catch (error) {
    console.error('CSV Generation Error:', error);
    if (Platform.OS === 'web') { window.alert('Failed to generate report.'); }
    else { Alert.alert('Error', 'Failed to generate report.'); }
  }
};

