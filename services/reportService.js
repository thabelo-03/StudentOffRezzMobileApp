export const generatePlatformOverviewPDF = async (users, houses) => {
  const students = users.filter(u => u.role === 'student').length;
  const landlords = users.filter(u => u.role === 'landlord').length;
  const admins = users.filter(u => u.role === 'admin').length;

  const stats = [
    { label: 'Total Users', value: users.length, color: '#007BFF' },
    { label: 'Students', value: students, color: '#4CAF50' },
    { label: 'Landlords', value: landlords, color: '#FF9800' },
    { label: 'Listings', value: houses.length, color: '#9C27B0' },
  ];

  // Location breakdown
  const locationCounts = {};
  houses.forEach(h => {
    const loc = h.location || 'Unknown';
    locationCounts[loc] = (locationCounts[loc] || 0) + 1;
  });

  const locHeaders = ['Location', 'Number of Listings', 'Percentage'];
  const locRows = Object.entries(locationCounts).map(([loc, count]) => [
    loc,
    count,
    `${((count / (houses.length || 1)) * 100).toFixed(1)}%`
  ]);

  const html = wrapHTML(
    getHeaderHTML('Platform Overview Report', `System snapshot — ${new Date().toDateString()}`) +
    getStatBoxHTML(stats) +
    '<h3>Listings by Location</h3>' +
    getTableHTML(locHeaders, locRows) +
    '<h3>User Role Distribution</h3>' +
    getTableHTML(['Role', 'Count', 'Percentage'], [
      ['Students', students, `${((students / (users.length || 1)) * 100).toFixed(1)}%`],
      ['Landlords', landlords, `${((landlords / (users.length || 1)) * 100).toFixed(1)}%`],
      ['Admins', admins, `${((admins / (users.length || 1)) * 100).toFixed(1)}%`],
    ]) +
    getFooterHTML()
  );

  await printOrShare(html, 'Platform_Overview');
};

