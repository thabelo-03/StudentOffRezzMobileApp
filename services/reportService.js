const buildHTML = (headerTitle, headerSubtitle, dateRange, body) => {
  const now = new Date();
  const dateStr = now.toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
  const timeStr = now.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' });

  return '<html><head><meta charset="utf-8"><style>' + PDF_STYLES + '</style></head><body>' +
    '<div class="header">' +
      '<div class="brand">ThabStay</div>' +
      '<div class="title">' + headerTitle + '</div>' +
      '<div class="subtitle">' + headerSubtitle + '</div>' +
      (dateRange ? '<div class="date-badge">📅 ' + dateRange + '</div>' : '') +
    '</div>' +
    body +
    '<div class="footer">' +
      '<div class="footer-left">Generated by <span class="footer-brand">ThabStay</span> &bull; ' + dateStr + ' at ' + timeStr + '</div>' +
      '<div class="footer-right">Confidential &bull; Page 1</div>' +
    '</div>' +
  '</body></html>';
};

const buildStatCards = (stats) => {
  let cards = '';
  for (let i = 0; i < stats.length; i++) {
    cards += '<div class="stat-card"><div class="stat-value" style="color:' + stats[i].color + ';">' + stats[i].value + '</div><div class="stat-label">' + stats[i].label + '</div></div>';
  }
  return '<div class="stats-row">' + cards + '</div>';
};

const buildTable = (headers, rows) => {
  let ths = '';
  for (let i = 0; i < headers.length; i++) ths += '<th>' + headers[i] + '</th>';
  let trs = '';
  for (let i = 0; i < rows.length; i++) {
    const isTotal = rows[i]._total;
    let tds = '';
    const cells = rows[i]._total ? rows[i].cells : rows[i];
    for (let j = 0; j < cells.length; j++) tds += '<td>' + cells[j] + '</td>';
    trs += '<tr' + (isTotal ? ' class="total-row"' : '') + '>' + tds + '</tr>';
  }
  if (rows.length === 0) {
    return '<div class="empty-state">No data found for the selected period</div>';
  }
  return '<table><thead><tr>' + ths + '</tr></thead><tbody>' + trs + '</tbody></table>';
};

const statusBadge = (status) => {
  const s = (status || '').toLowerCase();
  const cls = s === 'pending' ? 'badge-pending' : s === 'accepted' ? 'badge-accepted' : s === 'paid' ? 'badge-paid' : s === 'rejected' ? 'badge-rejected' : '';
  return '<span class="badge ' + cls + '">' + (s.charAt(0).toUpperCase() + s.slice(1)) + '</span>';
};

