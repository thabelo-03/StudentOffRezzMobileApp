const getHeaderHTML = (title, subtitle) => {
  return '<div style="background: linear-gradient(135deg, #007BFF, #0056b3); padding: 30px; color: white;">' +
    '<h1 style="margin:0; font-size:28px; font-weight:800;">ThabStay</h1>' +
    '<h2 style="margin:5px 0 0; font-size:20px; font-weight:400;">' + title + '</h2>' +
    '<p style="margin:5px 0 0; font-size:13px; opacity:0.85;">' + subtitle + '</p>' +
    '</div>';
};

const getFooterHTML = () => {
  const dateStr = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
  return '<div style="margin-top:30px; padding:15px; text-align:center; border-top:2px solid #eee; color:#999; font-size:11px;">' +
    'Generated by <strong>ThabStay</strong> &bull; ' + dateStr + ' &bull; Confidential' +
    '</div>';
};

const getStatBoxHTML = (stats) => {
  let boxes = '';
  for (let i = 0; i < stats.length; i++) {
    const s = stats[i];
    boxes += '<div style="flex:1; background:#f8f9fa; border-radius:10px; padding:15px; text-align:center; margin:0 5px; border-left:4px solid ' + s.color + ';">' +
      '<div style="font-size:24px; font-weight:bold; color:' + s.color + ';">' + s.value + '</div>' +
      '<div style="font-size:12px; color:#666; text-transform:uppercase; margin-top:5px;">' + s.label + '</div>' +
      '</div>';
  }
  return '<div style="display:flex; margin:20px 15px;">' + boxes + '</div>';
};

const getTableHTML = (headers, rows) => {
  let headerCells = '';
  for (let i = 0; i < headers.length; i++) {
    headerCells += '<th style="background:#007BFF; color:white; padding:10px 12px; text-align:left; font-size:12px; text-transform:uppercase;">' + headers[i] + '</th>';
  }

  let bodyRows = '';
  for (let i = 0; i < rows.length; i++) {
    const bg = i % 2 === 0 ? '#ffffff' : '#f8f9fb';
    let cells = '';
    for (let j = 0; j < rows[i].length; j++) {
      cells += '<td style="padding:10px 12px; border-bottom:1px solid #eee; font-size:13px; color:#333;">' + rows[i][j] + '</td>';
    }
    bodyRows += '<tr style="background:' + bg + ';">' + cells + '</tr>';
  }

  return '<table style="width:100%; border-collapse:collapse; margin:15px 0;">' +
    '<thead><tr>' + headerCells + '</tr></thead>' +
    '<tbody>' + bodyRows + '</tbody>' +
    '</table>';
};

const wrapHTML = (body) => {
  return '<html><head><meta charset="utf-8"><style>' +
    'body { font-family: Arial, Helvetica, sans-serif; margin:0; padding:0; color:#333; }' +
    'h3 { color:#333; margin:20px 15px 10px; font-size:18px; }' +
    '</style></head><body>' + body + '</body></html>';
};

