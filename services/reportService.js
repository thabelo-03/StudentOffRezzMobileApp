export const generatePropertiesPDF = async (listings, dateRange) => {
  const totalSpots = listings.reduce((a, h) => a + (Number(h.availableSpots) || 0), 0);
  const avgPrice = listings.length > 0 ? (listings.reduce((a, h) => a + (Number(h.price) || 0), 0) / listings.length).toFixed(0) : '0';

  const stats = [
    { label: 'Total Properties', value: listings.length, color: '#007BFF' },
    { label: 'Total Spots', value: totalSpots, color: '#4CAF50' },
    { label: 'Avg Price', value: '$' + avgPrice, color: '#FF9800' },
  ];

  const headers = ['#', 'Title', 'Location', 'Price', 'Spots', 'Gender'];
  const rows = listings.map((h, i) => [
    i + 1,
    h.title || 'N/A',
    h.location || 'N/A',
    '$' + (h.price || 0),
    h.availableSpots || 0,
    h.genderPolicy || 'Mixed'
  ]);

  const subtitle = dateRange || ('Generated on ' + new Date().toDateString());
  const html = wrapHTML(
    getHeaderHTML('Properties Report', subtitle) +
    getStatBoxHTML(stats) +
    '<h3>Property Listings</h3>' +
    getTableHTML(headers, rows) +
    getFooterHTML()
  );

  await exportPDF(html, 'Properties_Report');
};

