export const exportPDF = async (html, filename) => {
  try {
    if (Platform.OS === 'web') {
      const printWindow = window.open('', '_blank');
      if (printWindow) {
        printWindow.document.write(html);
        printWindow.document.close();
        printWindow.focus();
        setTimeout(function() { printWindow.print(); }, 500);
      }
    } else {
      // Use printAsync for native preview (shows print dialog with preview)
      await Print.printAsync({ html: html });
    }
  } catch (error) {
    console.error('PDF Error:', error);
    if (Platform.OS === 'web') { window.alert('Failed to generate PDF.'); }
    else { Alert.alert('Error', 'Failed to generate PDF: ' + (error.message || '')); }
  }
};

export const sharePDF = async (html, filename) => {
  try {
    if (Platform.OS === 'web') {
      await exportPDF(html, filename);
      return;
    }
    const result = await Print.printToFileAsync({ html: html, width: 612, height: 792 });
    const newUri = FileSystem.documentDirectory + filename + '_' + Date.now() + '.pdf';
    await FileSystem.moveAsync({ from: result.uri, to: newUri });
    const canShare = await Sharing.isAvailableAsync();
    if (canShare) {
      await Sharing.shareAsync(newUri, { mimeType: 'application/pdf', dialogTitle: 'Share ' + filename, UTI: 'com.adobe.pdf' });
    } else {
      Alert.alert('Success', 'PDF saved successfully.');
    }
  } catch (error) {
    console.error('Share PDF Error:', error);
    Alert.alert('Error', 'Failed to share PDF: ' + (error.message || ''));
  }
};
