// ============================
// Helper: Print or Share PDF
// ============================

const printOrShare = async (html, filename) => {
  try {
    const { uri } = await Print.printToFileAsync({ html });
    
    // Rename file
    const newUri = FileSystem.documentDirectory + `${filename}_${Date.now()}.pdf`;
    await FileSystem.moveAsync({ from: uri, to: newUri });

    const canShare = await Sharing.isAvailableAsync();
    if (canShare) {
      await Sharing.shareAsync(newUri, { mimeType: 'application/pdf', dialogTitle: `Share ${filename}` });
    } else {
      Alert.alert('Success', `Report saved to: ${newUri}`);
    }
  } catch (error) {
    console.error('PDF Generation Error:', error);
    Alert.alert('Error', 'Failed to generate PDF report.');
  }
};
